#!/usr/bin/env node
// Runs one bird in the LBM tunnel, in GPU lock holds under 10 minutes, resuming from checkpoints.
//
//   node tunnel/lbm/run-design.mjs <design> [--wingbeats N] [--dx m] [--speed m/s] [--freq Hz]
//        [--amp rad] [--full] [--ulat 0.12] [--cs 0.16] [--relink K] [--run name]
//
// --relink 2 (default) rebuilds the wing links every second step. On larus-gl-2 at 10 mm it moved
// per-wingbeat lift by at most 1.2% against every step, inside the 2% beat-to-beat spread, at 1.5x speed.
//
// <design> is a name in data/designs or a path. Writes out/lbm/<run>.json with cycle-resolved lift,
// thrust and moments per wing and body. Half model with a symmetry plane unless --full.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const argv = process.argv.slice(2);
const flag = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : undefined; };
const num = (n) => { const v = flag(n); return v === undefined ? undefined : Number(v); };
const designArg = argv[0];
if (!designArg || designArg.startsWith('--')) { console.error('usage: run-design.mjs <design> [--wingbeats N] [--dx m] [--speed m/s] [--freq Hz] [--full] [--run name]'); process.exit(2); }
const designPath = fs.existsSync(designArg) ? designArg : path.join(ROOT, 'data/designs', designArg.endsWith('.json') ? designArg : `${designArg}.json`);
const designText = fs.readFileSync(designPath, 'utf8');
const designFile = JSON.parse(designText);
// Designs are regenerated by src/design; record exactly which version this run used.
const designSha256 = (await import('node:crypto')).createHash('sha256').update(designText).digest('hex');
const stem = path.basename(designPath, '.json');
const dx = num('--dx') ?? 0.005, wingbeats = num('--wingbeats') ?? 3;
const run = flag('--run') ?? `${stem}-dx${(dx * 1000).toFixed(1)}mm-${wingbeats}wb`;
const args = { designFile, name: run, dx, wingbeats, speed: num('--speed'), freq: num('--freq'), amp: num('--amp'), half: !argv.includes('--full'), uLat: num('--ulat'), csSmag: num('--cs'), relink: num('--relink') };
const outFile = path.join(ROOT, 'out/lbm', `${run}.json`);
const work = path.join(ROOT, 'out/lbm/runs', `${run}.work.json`);
fs.mkdirSync(path.dirname(work), { recursive: true });
fs.rmSync(work, { force: true });
const jobs = JSON.stringify([{ job: 'runDesign', key: 'r', args }]);
const hold = +(process.env.RUN_DESIGN_HOLD_S ?? 480);
for (let h = 0; h < 200; h++) {
  const r = spawnSync('python3', [path.join(ROOT, 'tools/run-guarded.py'), '--timeout', String(hold + 110), '--gpu', '--log', path.join(ROOT, 'out/lbm/runs', `${run}.log`), '--',
    'node', path.join(HERE, 'tools/job.mjs'), work, jobs], { env: { ...process.env, JOB_SECONDS: String(hold) }, stdio: 'inherit' });
  const res = fs.existsSync(work) ? JSON.parse(fs.readFileSync(work, 'utf8')).r : null;
  console.log(`hold ${h + 1}: exit ${r.status}${res?.done === false ? `, ${res.n}/${res.total} steps, ${Math.round(res.mlups)} MLUPS` : ''}`);
  if (r.status === 0 && res?.done) {
    res.design_file = path.relative(ROOT, designPath);
    res.design_sha256 = designSha256;
    res.command = `node tunnel/lbm/run-design.mjs ${argv.join(' ')}`;
    fs.writeFileSync(outFile, JSON.stringify(res));
    fs.rmSync(work, { force: true });
    const c = res.cost;
    console.log(JSON.stringify({ out: path.relative(ROOT, outFile), cells: res.grid.cells, dx, tau0: res.params.tau0, mlups: Math.round(c.mlups), seconds_per_wingbeat: Math.round(c.seconds_per_wingbeat), per_wingbeat: res.per_wingbeat }));
    process.exit(0);
  }
  if (r.status !== 75) { console.error(`run-design: child failed with ${r.status}; log in out/lbm/runs/${run}.log`); process.exit(1); }
    // Let anyone else queued on the GPU lock in: run-guarded polls it every 2 s.
    spawnSync('sleep', ['5']);
}
process.exit(1);
